import os
import re

node_modules = os.path.join("node_modules")

problematic_files = []

for root, dirs, files in os.walk(node_modules):
    # skip .git or cache
    if ".cache" in root or ".git" in root:
        continue
    for file in files:
        if file.endswith(".js") or file.endswith(".mjs"):
            filepath = os.path.join(root, file)
            try:
                with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
                    content = f.read()
                    if ".bind(" in content and ("import " in content or "require(" in content):
                        # search for import X from "..." followed by X.bind or similar
                        if "mergeOptions.bind" in content or "Reflect.get.bind()" in content or "serializableMappingCache" in content:
                            problematic_files.append(filepath)
            except Exception as e:
                pass

print("Problematic files found:")
for p in problematic_files:
    print(p)
